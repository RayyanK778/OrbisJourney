// Step 8: Report. Writes docs/data-report.md. The report is committed, so comparing it
// between commits shows how the data changed. It contains no timestamps, so an
// unchanged build produces an identical file.
import type { Entity, SourceInfo } from '../../shared/schema.ts';
import { formatOpenRange, formatRange, formatYear } from '../../shared/years.ts';
import { CHECKS, PROVISIONAL_CONFIDENCE, YEAR_RANGE } from '../config.ts';
import type { Issue } from '../lib/issues.ts';
import type { CorrectionResult } from './correct.ts';
import type { EncodeResult } from './encode.ts';
import type { IdentifyResult } from './identify.ts';
import type { NormalizeResult } from './normalize.ts';
import type { OverlapStats } from './overlaps.ts';
import type { FinalRecord } from './validate.ts';

export interface ReportInput {
  sources: SourceInfo[];
  normalized: NormalizeResult;
  identified: IdentifyResult;
  corrected: CorrectionResult;
  records: FinalRecord[];
  issues: Issue[];
  overlapStats: OverlapStats;
  encoded: EncodeResult | null;
}

const num = (n: number) => n.toLocaleString('en-US');
const mb = (bytes: number) => `${(bytes / 1e6).toFixed(2)} MB`;
const kb = (bytes: number) => `${Math.round(bytes / 1e3)} KB`;
/** Escapes text for a Markdown table cell. */
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (head: string[], rows: string[][]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.map(cell).join(' | ')} |`)].join('\n');

const CHECK_TITLES: Record<string, string> = {
  overlap: 'Filled territories overlapping',
  'area-jump': 'Sudden area changes',
  'entity-overlap': 'One entity filled twice at once',
  'group-missing': 'Groupings named in MemberOf but missing',
  'grouping-shape': 'Grouping names and components disagree',
  'overlap-check-failed': 'Shapes the overlap check could not compare',
};

export function renderReport(input: ReportInput): string {
  const { normalized, identified, corrected, records, issues, encoded } = input;
  const errors = issues.filter(i => i.level === 'error');
  const warnings = issues.filter(i => i.level === 'warning');
  const leaves = records.filter(r => !r.isGrouping);
  const curated = identified.entities.filter(e => e.curated);
  const out: string[] = [];
  /** Adds blocks (headings, paragraphs, tables, whole lists) separated by blank lines. */
  const push = (...blocks: string[]) => out.push(...blocks.filter(Boolean).map(b => `${b}\n`));
  const list = (items: string[]) => items.map(i => `- ${i}`).join('\n');

  push(
    '# Data build report',
    '> Generated by `npm run data:build`. Don\'t edit this file by hand: the next build overwrites it. ' +
      'Comparing it between commits shows how the data changed.',
  );

  // --- Summary ---
  const totalGzip = encoded ? Object.values(encoded.index.chunks).reduce((s, c) => s + c.gzipBytes, 0) : 0;
  const largest = encoded ? Object.entries(encoded.index.chunks).sort((a, b) => b[1].gzipBytes - a[1].gzipBytes)[0] : undefined;
  push(
    '## Summary',
    table(['', ''], [
      ['Result', errors.length ? `**Failed** with ${errors.length} errors. No site data was written.` : '**Passed**'],
      [`Source records overlapping ${formatRange(YEAR_RANGE.min, YEAR_RANGE.max)}`, `${num(normalized.records.length)} of ${num(normalized.totalInSource)}`],
      ['Records after corrections', `${num(records.length)} (${num(leaves.length)} filled, ${num(records.length - leaves.length)} groupings)`],
      ['Entities', `${num(identified.entities.length)} (${curated.length} curated, ${num(identified.entities.length - curated.length)} generated from one name each)`],
      ['Corrections applied', `${corrected.applied.length}, changing ${num(corrected.applied.reduce((s, a) => s + a.records, 0))} records`],
      ['Errors', String(errors.length)],
      ['Warnings to review', num(warnings.length)],
      ...(encoded && largest
        ? [
            ['Site data', `${Object.keys(encoded.index.chunks).length} chunk files, ${mb(totalGzip)} gzipped in total`],
            ['Largest chunk', `${largest[0]}s: ${mb(largest[1].gzipBytes)} gzipped`],
            ['Years with a border change', num(encoded.index.changeYears.length)],
          ]
        : []),
    ]),
  );

  // --- Sources ---
  push(
    '## Sources',
    table(['Source', 'Version', 'License', 'SHA-256'], input.sources.map(s => [`[${s.id}](${s.url})`, s.version, s.license, `\`${s.sha256.slice(0, 16)}…\``])),
  );

  // --- Interpretation ---
  const levels = [1, 2, 3].map(q => records.filter(r => r.confidence === q).length);
  push(
    '## How the source is read',
    list([
      `**Year 0.** Cliopatria doesn't say how it numbers years around 0. The pipeline reads a source year 0 as 1 BCE, which affected ${normalized.yearZeroFixes.length} records: ` +
        normalized.yearZeroFixes.map(f => `${f.name} (${f.field === 'to' ? 'end' : 'start'})`).join(', ') + '.',
      '**Groupings.** Names in parentheses, such as "(British Empire)", are composites whose shapes repeat their members\' shapes. They are drawn as outlines, never filled.',
      '**Confidence (provisional).** Cliopatria has no per-record certainty, so the starting level comes from the year a record begins: ' +
        PROVISIONAL_CONFIDENCE.map((r, i) => {
          const prev = PROVISIONAL_CONFIDENCE[i - 1]?.before;
          const span = prev === undefined ? `before ${formatYear(r.before)}` : r.before === Infinity ? `from ${formatYear(prev)}` : `${formatYear(prev)} to ${formatYear(r.before - 1)}`;
          return `${span} → ${r.level}`;
        }).join('; ') + `. Records per level: 1 approximate ${num(levels[0])}, 2 moderate ${num(levels[1])}, 3 legally defined ${num(levels[2])}. Phase 3 sets the real rules.`,
    ]),
  );

  // --- Corrections ---
  push(
    '## Corrections',
    'Fixes in `data/corrections/`, applied at build time without editing the source. ' +
      'A correction that covers only part of a record splits it into pieces with the same shape.',
    table(
      ['ID', 'Source name', 'Years', 'New label', 'Records', 'Citations'],
      corrected.applied.map(a => [
        `\`${a.correction.id}\``,
        a.correction.match.name,
        formatOpenRange(a.correction.match.from, a.correction.match.to),
        a.correction.change.label,
        a.splits ? `${a.records} (${a.splits} split)` : String(a.records),
        a.correction.citations.map(c => `[${c.title}](${c.url})`).join(', '),
      ]),
    ),
  );

  // --- Curated entities ---
  const claims = (e: Entity) => identified.curatedClaims.filter(c => c.entityId === e.id);
  push(
    '## Curated entities',
    'Identities in `data/entities/entities.json` that join several source names. Every other name becomes its own entity.',
    table(['Entity', 'Display name', 'Source names (records)'], curated.map(e => [
      `\`${e.id}\``,
      e.displayName,
      claims(e).map(c => `${c.rule} (${c.records})`).join('; '),
    ])),
  );

  // --- Validation ---
  push('## Validation');
  if (errors.length) push('### Errors', 'These stop the build.', list(errors.map(e => `**${e.check}**: ${e.message}`)));
  else push('No errors.');

  const byCheck = new Map<string, Issue[]>();
  for (const w of warnings) byCheck.set(w.check, [...(byCheck.get(w.check) ?? []), w]);
  push(
    '### Warnings',
    'Warnings need review but don\'t stop the build: many are real history, such as occupations and vassal states. ' +
      `Each list shows the largest ${CHECKS.reportRows}; \`data/build/validation.json\` has all of them.`,
    table(['Check', 'Count'], [...byCheck].map(([check, found]) => [CHECK_TITLES[check] ?? check, num(found.length)])),
  );
  const s = input.overlapStats;
  for (const [check, found] of byCheck) {
    const sorted = [...found].sort((a, b) => (b.weight ?? 0) - (a.weight ?? 0) || a.message.localeCompare(b.message));
    push(
      `#### ${CHECK_TITLES[check] ?? check}`,
      check === 'overlap'
        ? `Pairs that cover at least ${num(CHECKS.overlapMinKm2)} km² in common, or at least ${CHECKS.overlapMinShare * 100}% of the smaller territory. ` +
          `${num(s.candidates)} pairs of shapes were compared.`
        : check === 'area-jump'
          ? `Consecutive records of one entity whose area changes at least ${CHECKS.areaJumpRatio}× and by at least ${num(CHECKS.areaJumpMinKm2)} km².`
          : '',
      list([
        ...sorted.slice(0, CHECKS.reportRows).map(w => w.message),
        ...(sorted.length > CHECKS.reportRows ? [`…and ${num(sorted.length - CHECKS.reportRows)} more.`] : []),
      ]),
    );
  }

  // --- Review queue: generated entities sharing a Wikidata ID ---
  const byWikidata = new Map<string, Entity[]>();
  for (const e of identified.entities)
    if (e.wikidataId && !e.curated) byWikidata.set(e.wikidataId, [...(byWikidata.get(e.wikidataId) ?? []), e]);
  const shared = [...byWikidata].filter(([, group]) => group.length > 1).sort((a, b) => a[0].localeCompare(b[0], 'en', { numeric: true }));
  push(
    '## Review queue: names that share a Wikidata ID',
    `${shared.length} Wikidata IDs are shared by more than one generated entity. Some are one polity under several names and could be merged into a curated entity. ` +
      'Others are wrong links in the source, such as Assyria and Syria, so none are merged automatically.',
    '<details><summary>Show the list</summary>',
    '',
    table(['Wikidata', 'Names'], shared.map(([id, group]) => [`[${id}](https://www.wikidata.org/wiki/${id})`, group.map(e => e.aliases[0]).join(' · ')])),
    '',
    '</details>',
  );

  // --- Output ---
  if (encoded) {
    // Chunk "0" starts at year 0, which doesn't exist, so it really covers 1–99 CE
    const chunkYears = (start: number) =>
      formatRange(Math.max(start === 0 ? 1 : start, YEAR_RANGE.min), Math.min(start + encoded.index.chunkSize - 1, YEAR_RANGE.max));
    push(
      '## Output files',
      'Written to `data/build/`, which is not committed.',
      '<details><summary>Chunk sizes</summary>',
      '',
      table(['Chunk', 'Years', 'Records', 'Gzipped'], Object.entries(encoded.index.chunks)
        .sort((a, b) => Number(a[0]) - Number(b[0]))
        .map(([start, c]) => [c.file, chunkYears(Number(start)), num(c.records), kb(c.gzipBytes)])),
      '',
      '</details>',
    );
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}
